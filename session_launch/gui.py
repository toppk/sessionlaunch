    def set_agent_messages(self, messages):
        view = (self.selected_ref(), id(messages))
        if view == getattr(self, "_message_view", None) and self.message_content.isVisible():
            return
        self._message_view = view
        self.message_header.show()
        self.message_content.show()
        self.message_heading_labels = []
        while self.message_layout.count():
            item = self.message_layout.takeAt(0)
            widget = item.widget()
            if widget:
                widget.hide()
                widget.setParent(None)
                widget.deleteLater()
        if messages is None or isinstance(messages, str) or not messages:
            label = QLabel("Loading last messages…" if messages is None else
                           messages if isinstance(messages, str) else "No messages found.")
            label.setObjectName("muted")
            self.message_layout.addWidget(label)
            return
        for message in messages:
            card = QFrame()
            card.setObjectName("messageCard")
            layout = QVBoxLayout(card)
            layout.setContentsMargins(12, 10, 12, 10)
            layout.setSpacing(5)
            role = str(message.get("role") or "message").upper()
            stamp = format_datetime(message.get("timestamp"))
            heading = QLabel(f"{role}  ·  {stamp}")
            heading.setObjectName("muted")
            layout.addWidget(heading)
            self.message_heading_labels.append((heading, role, message.get("timestamp")))
            content = str(message.get("content") or "").strip() or "[No text]"
            body = QLabel(content[:700] + "…" if len(content) > 700 else content)
            body.setTextFormat(Qt.PlainText)
            body.setWordWrap(True)
            body.setTextInteractionFlags(Qt.TextSelectableByMouse)
            layout.addWidget(body)
            if len(content) > 700:
                expand = QPushButton("Show full message")
                expand.clicked.connect(lambda checked=False, label=body, button=expand,
                                              full=content: self.toggle_message(label, button, full))
                layout.addWidget(expand, 0, Qt.AlignLeft)
            self.message_layout.addWidget(card)

