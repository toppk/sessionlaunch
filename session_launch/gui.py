    def place_members(self, refs, target, before):
        """Order rows within a group; dropping across sections moves the rows there."""
        nav = self.navigation_ref()
        group_id = (nav[1] if nav and nav[0] in ("group", "unsectioned") else
                    self.groups.section(nav[1])[0] if nav and nav[0] == "section" and
                    self.groups.section(nav[1]) else None)
        if not group_id:
            return
        section_id = self.section_for_ref(target, group_id)
        scope = section_id or group_id
        target_key = self.member_key_for_ref(target)
        keys = list(dict.fromkeys(self.member_key_for_ref(ref) for ref in refs))
        keys = [key for key in keys if key and key != target_key]
        if not keys:
            return
        visible_keys = []
        for index in range(self.session_model.rowCount()):
            row_ref = self.session_model.index(index, 0).data(SessionListModel.RefRole)
            if not row_ref or row_ref[0] not in ("terminal", "saved", "agent"):
                continue
            if group_id not in self.groups.groups_for(self.group_keys_for_ref(row_ref)) or \
                    self.section_for_ref(row_ref, group_id) != section_id:
                continue
            key = self.member_key_for_ref(row_ref)
            if key and key not in visible_keys:
                visible_keys.append(key)
        def place():
            self.groups.assign_section(self.group_keys_for_refs(refs), group_id, section_id)
            for key in reversed(keys):
                self.groups.place_member(scope, key, target_key, before,
                                         [*visible_keys, *keys])
        self.change_group(place)

