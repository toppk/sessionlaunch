                roles = ", ".join(f"r:{value}" for value in markers["r"])
                tasks = ", ".join(f"t:{value}" for value in markers["t"])
                peer = f"  ↔ {member['peer']['name']}" if member["peer"] else ""
                dot = "●" if member["running"] else "○"
