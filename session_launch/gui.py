    def navigation_contains(self, ref):
        scope = self.navigation_ref()
        if not scope:
            return False
        if scope[0] == "all":
            return True
        keys = self.group_keys_for_ref(ref)
        retired = self.groups.is_retired(keys)
        kind, identifier = scope
        if kind == "retired":
            return retired
        if retired and self.keep_view == "kept":
            return False
        memberships = self.groups.memberships_for(keys)
        groups = {entry["group"] for entry in memberships}
        domains = self.groups.domains_for(keys)
        if kind == "standing":
            return self.groups.is_standing(keys)
        if kind == "group":
            return identifier in groups
        if kind == "section":
            found = self.groups.section(identifier)
            return bool(found and any(entry == {"group": found[0], "section": identifier}
                                      for entry in memberships))
        if kind == "unsectioned":
            return any(entry == {"group": identifier, "section": ""}
                       for entry in memberships)
        if kind == "domain":
            return identifier in domains
        if kind == "domain_ungrouped":
            return identifier in domains and not any(
                (group := self.groups.get(group_id)) and group.get("domain") == identifier
                for group_id in groups)
        if kind == "domains":
            return bool(domains)
        if kind == "no_domain":
            return any(group["id"] in groups and not group.get("domain")
                       for group in self.groups.groups)
        if kind == "ungrouped":
            return not groups and not domains
        return False

    def row_matches_filters(self, ref, status, tags, text, provider="", activity="",
                            elevated=False, host=""):
        if self.navigation_ref() != ("retired", ""):
            set_aside = self.groups.is_retired(self.group_keys_for_ref(ref))
            if self.keep_view == "kept" and set_aside or \
                    self.keep_view == "set_aside" and not set_aside:
                return False
        if self.search.text().casefold() not in text.casefold():
            return False
        if self.active_tags and not self.active_tags.intersection(tags):
            return False
        if self.provider_filter == "claude-peer":
            if provider != "claude" or not any(tag.startswith("peer:") for tag in tags):
                return False
        elif self.provider_filter and provider != self.provider_filter:
            return False
        currently_running = status in LIVE_STATUSES
        if self.age_filter and activity and not currently_running:
            try:
                when = datetime.fromisoformat(str(activity).replace("Z", "+00:00"))
                days = 7 if self.age_filter == "7d" else 30
                if when.tzinfo is None:
                    when = when.replace(tzinfo=timezone.utc)
                if when < datetime.now(timezone.utc) - timedelta(days=days):
                    return False
            except ValueError:
                return False
        if self.age_filter and not activity and not currently_running:
            return False
        if self.active_facets:
            state = "saved" if status in ("resumable", "frozen", "closed") else "live"
            facets = record_facets(state, host, elevated)
            for section in ("activity", "access"):
                selected = {entry.partition(":")[2] for entry in self.active_facets
                            if entry.startswith(section + ":")}
                if selected and facets[section] not in selected:
                    return False
        in_scope = self.navigation_contains(ref)
        bucket = "running" if currently_running else "not_running"
        if in_scope:
            self._status_counts[bucket] += 1
        elif self.search.text() and (self.presence_view == "all" or
                                     self.presence_view == bucket):
            self._outside_search_refs.add(ref)
        return in_scope and (self.presence_view == "all" or self.presence_view == bucket)

    def refresh_list(self):
        """Build one card per identity, then apply the selected navigation scope."""
        self._status_counts = {"running": 0, "not_running": 0}
        self._outside_search_refs = set()
        terminals = self.live_data.get("terminal", [])
        live_by_key = {terminal_session_key(item): item for item in terminals
                       if item.get("state") == "live"}
        visible = []
        self.agent_by_id = {row["id"]: row for row in self.agent_rows}
        known = set()
        for row in self.standing_agent_rows():
            key = agent_session_key(row.get("agent"), row.get("id"))
            if not key or key in known:
                continue
            known.add(key)
            linked = live_by_key.get(key)
            peer = claude_peers.peer_for(row["id"], self.claude_peers)
            status = "running" if linked or peer or key in self.terminals else "resumable"
            directory = row.get("cwd") or (terminal_directory(linked)[0] if linked else "")
            title = row.get("display_name") or row.get("project") or row["id"]
            tags = [row["agent"], f"{row.get('message_count') or 0} msgs"]
            repo = repo_tag_for(directory) if directory else None
            if repo:
                tags.append(repo)
            if peer:
                tags.append(f"peer:{peer['name']}")
            ref = ("agent", row["id"])
            text = " ".join((title, row["id"], directory, *tags,
                             self.annotation_for_ref(ref)))
            if self.view == "sessions" and self.row_matches_filters(
                    ref, status, tags, text, row["agent"], row.get("ended_at") or "",
                    host=linked.get("host_application", "") if linked else ""):
                source = f"Session {row['id']} · Last transcript: {format_agent_activity(row.get('ended_at'))}"
                visible.append((ref, title, short_home(directory), status, tags, source, False))

        historical = {}
        for terminal in terminals:
            key = terminal_session_key(terminal)
            if terminal.get("state") == "live" or key in live_by_key:
                continue
            if key not in historical or terminal.get("closed_at", "") > \
                    historical[key].get("closed_at", ""):
                historical[key] = terminal
        for terminal in [*live_by_key.values(), *historical.values()]:
            key = terminal_session_key(terminal)
            provider = terminal.get("agent") or ""
            if key.startswith("agent:"):
                if key not in known:
                    _, agent, session_id = key.split(":", 2)
                    row_id = f"codex:{session_id}" if agent == "codex" else session_id
                    placeholder = {"id": row_id, "agent": agent,
                                   "cwd": terminal.get("agent_cwd") or terminal_directory(terminal)[0],
                                   "display_name": f"Session {session_id[:8]}",
                                   "project": "", "message_count": 0}
                    self.agent_by_id[row_id] = placeholder
                    known.add(key)
                    self.agent_rows.append(placeholder)
                continue
            if key.startswith("saved:"):
                continue
            view = "sessions" if provider in ("claude", "codex") else "plain"
            if self.view != view:
                continue
            state = terminal.get("state")
            host = terminal.get("host_application") or terminal.get("comm") or "Shell"
            status = ("terminal only" if view == "sessions" and state == "live" else
                      display_status(state, host) if state == "live" else "closed")
            directory = terminal_directory(terminal)[0]
            tags = self.tags_for_terminal(terminal)
            ref = ("terminal", terminal["key"])
            text = " ".join((host, terminal.get("terminal", ""), directory,
                             terminal.get("pty", ""), *tags, self.annotation_for_ref(ref)))
            elevated = bool(elevation_reason(terminal))
            if self.row_matches_filters(ref, status, tags, text, provider,
                                        terminal.get("closed_at", "") if state != "live" else "",
                                        elevated, host):
                visible.append((ref, host, terminal_list_directory(terminal),
                                display_status(state, host), list(tags),
                                f"Host CWD: {short_home(directory)}", elevated))

        if self.view == "frozen":
            for saved in self.live_data.get("saved", []):
                ref = ("saved", saved["id"])
                directory = saved.get("directory", "")
                tags = self.tags_for_saved(saved)
                linked = linked_terminal_for_saved(saved, terminals)
                host = (linked.get("host_application") or linked.get("comm") or "bash") if linked else ""
                status = display_status("live", host) if linked else "frozen"
                text = " ".join((saved["title"], directory,
                                 *saved.get("command_argv", []), *tags,
                                 self.annotation_for_ref(ref)))
                if self.row_matches_filters(ref, status, tags, text,
                                            activity=saved.get("captured_at", ""), host=host):
                    visible.append((ref, saved["title"], short_home(directory),
                                    status if linked else "saved",
                                    list(tags), "Frozen command: " +
                                    shlex.join(saved.get("command_argv", [])), False))

        metadata_keys = (set(self.groups.memberships) | set(self.groups.annotations) |
                         set(self.groups.standing) | set(self.groups.session_domains) |
                         set(self.groups.lifecycle) | set(self.groups.retired))
        observed_keys = {terminal_session_key(item) for item in terminals}
        observed_keys.update(f"saved:{saved['id']}" for saved in self.live_data.get("saved", []))
        for key in sorted(metadata_keys - observed_keys):
            if key.startswith("terminal:") and self.view == "plain":
                ref, status, title = (("terminal", key.removeprefix("terminal:")),
                                      "closed", "Terminal record")
            elif key.startswith("saved:") and self.view == "frozen":
                ref, status, title = (("saved", key.removeprefix("saved:")),
                                      "frozen", "Frozen command record")
            else:
                continue
            if self.row_matches_filters(ref, status, set(),
                                        title + " " + self.annotation_for_ref(ref)):
                visible.append((ref, title, "CWD unavailable", "saved", [],
                                "Stored organization record", False))

        scope = self.navigation_ref()
        positions = {key: index for index, key in enumerate(
            self.groups.member_order.get(scope[1], []))} if scope else {}
        def order(pair):
            index, row = pair
            ref = row[0]
            agent = self.agent_by_id.get(ref[1], {}) if ref[0] == "agent" else {}
            activity = agent.get("ended_at") or ""
            timestamp = agent.get("started_at") if self.sort_filter == "started:desc" else activity
            try:
                recent = datetime.fromisoformat(str(timestamp).replace("Z", "+00:00")).timestamp()
            except (ValueError, TypeError):
                recent = 0
            secondary = (-int(agent.get("message_count") or 0) if self.sort_filter == "messages:desc"
                         else -recent)
            return (annotation_hierarchy_key(self.annotation_for_ref(ref)),
                    positions.get(self.member_key_for_ref(ref), len(positions)), secondary,
                    index)
        visible = [row for _, row in sorted(enumerate(visible), key=order)]
        if self.presence_view == "all" and self.split_sessions:
            running = [row for row in visible if row[3] in LIVE_STATUSES]
            stopped = [row for row in visible if row[3] not in LIVE_STATUSES]
            visible = [(("split", "running"), f"RUNNING · {len(running)}", "", "", [], "", False),
                       *running,
                       (("split", "not_running"), f"NOT RUNNING · {len(stopped)}", "", "", [], "", False),
                       *stopped]
        self.render_rows(visible)

    def render_rows(self, visible):
        total_records = sum(row[0][0] != "split" for row in visible)
        selected = self.session_list.currentIndex().data(SessionListModel.RefRole)
        selected_refs = [index.data(SessionListModel.RefRole)
                         for index in self.session_list.selectedIndexes()]
        previous_refs = [row[SessionListModel.RefRole] for row in self.session_model.rows]
        selected_row = previous_refs.index(selected) if selected in previous_refs else 0
        top_index = self.session_list.indexAt(QPoint(8, 2))
        top_ref = top_index.data(SessionListModel.RefRole) if top_index.isValid() else None
        top_offset = self.session_list.visualRect(top_index).top() if top_index.isValid() else 0
        old_scroll = self.session_list.verticalScrollBar().value()
        selection = self.session_list.selectionModel()
        selection.blockSignals(True)
        self.session_model.set_rows(visible)
        current = self.session_model.index_for_ref(selected)
        if not current.isValid() and self._detail_focus == "session":
            candidates = [row for row in range(self.session_model.rowCount())
                          if self.session_model.index(row, 0).data(
                              SessionListModel.RefRole)[0] != "split"]
            if candidates:
                current = self.session_model.index(
                    min(candidates, key=lambda row: abs(row - selected_row)), 0)
        if current.isValid() and self._detail_focus == "session":
            self.session_list.setCurrentIndex(current)
        else:
            selection.clearCurrentIndex()
            if self._detail_focus == "session":
                self._detail_focus = "navigation"
        for ref in selected_refs:
            index = self.session_model.index_for_ref(ref)
            if index.isValid():
                selection.select(index, QItemSelectionModel.Select)
        if top_ref not in self.session_model.positions and top_ref in previous_refs:
            top_row = previous_refs.index(top_ref)
            top_ref = next((ref for ref in previous_refs[top_row + 1:]
                            if ref in self.session_model.positions),
                           next((ref for ref in reversed(previous_refs[:top_row])
                                 if ref in self.session_model.positions), None))
        anchor = self.session_model.index_for_ref(top_ref)
        if anchor.isValid():
            self.session_list.scrollTo(anchor, QAbstractItemView.PositionAtTop)
            bar = self.session_list.verticalScrollBar()
            bar.setValue(bar.value() - top_offset)
        elif previous_refs:
            self.session_list.verticalScrollBar().setValue(old_scroll)
        selection.blockSignals(False)
