        layout = QVBoxLayout(self)
        heading = QLabel(f"{provider} in {short_home(cwd)}")
        heading.setObjectName("subject")
        layout.addWidget(heading)
        self.notice = QLabel("Querying AgentsView for sessions in this exact directory…")
        self.notice.setWordWrap(True)
        layout.addWidget(self.notice)
