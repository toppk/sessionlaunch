    def set_rows(self, rows):
        """Reset visible rows; the view restores current ref and scroll anchor."""
        window = self.window
        agent_terminals = {terminal["key"] for terminal in window.live_data.get("terminal", [])
                           if terminal.get("agent") in ("claude", "codex")}
        terminals = {row["key"]: row for row in window.live_data.get("terminal", [])}
        catalog = {agent_session_key(row.get("agent"), row.get("id", "")): row
                   for row in window.agent_rows}
        role_counts = Counter(value for line in window.groups.annotations.values()
                              for value in set(annotation_markers(line)["r"]))
        role_order = {role: index for index, line in
                      enumerate(window.groups.annotations.values())
                      for role in annotation_markers(line)["r"]}
        prepared = []
        scope = window.navigation_ref()
        current_group = (scope[1] if scope and scope[0] == "group" else
                         window.groups.section(scope[1])[0] if scope and scope[0] == "section"
                         and window.groups.section(scope[1]) else None)
        for ref, command, directory, status, tags, _source, elevated in rows:
            if ref[0] == "split":
                prepared.append({Qt.DisplayRole: command, self.RefRole: ref,
                                 Qt.SizeHintRole: QSize(0, max(25, 28 + window.zoom))})
                continue
            identity_keys = window.group_keys_for_ref(ref)
            annotation = window.annotation_for_ref(ref)
            markers = annotation_markers(annotation)
            shown_tags = [*tags]
            shown_tags.extend(f"{kind}:{value}" for kind in ("r", "o", "t")
                              for value in markers[kind])
            shown_tags.sort(key=lambda tag: (0 if tag.startswith("peer:") else
                                             1 if tag.startswith("r:") else
                                             2 if tag.startswith("o:") else
                                             3 if tag.startswith("t:") else
                                             4 if tag.startswith("repo:") else
                                             5 if tag.startswith("section:") else 6, tag))
            agent = window.agent_by_id.get(ref[1], {}) if ref[0] == "agent" else {}
            terminal = terminals.get(ref[1], {}) if ref[0] == "terminal" else {}
            provider = agent.get("agent", "") or terminal.get("agent", "")
            session_key = agent_session_key(provider, agent.get("id", "") if agent else
                                            terminal.get("session_id", ""))
            session_id = session_key.rsplit(":", 1)[-1] if session_key else ""
            card_status = card_presence(ref, status, provider, session_id)
            if ref[0] == "saved" and not any(saved["id"] == ref[1]
                                              for saved in window.live_data.get("saved", [])):
                card_status = "record only"
            transcript = (agent or catalog.get(session_key) or {}).get("ended_at")
            repo_tag = next((tag for tag in shown_tags if tag.startswith("repo:")), "")
