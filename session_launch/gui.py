def display_status(state, host=""):
    """Classify what is observed now, without declaring a saved record dead."""
    if state not in ("live", "open", "starting"):
        return "saved"
    return "idle" if host.removeprefix("-").casefold() in SHELLS else "running"


def card_presence(ref, presence, provider, session_id):
    """Distinguish a resumable session from a terminal with no proven UUID."""
    if (ref[0] == "terminal" and provider in ("claude", "codex")
            and not session_id and presence in ("running", "idle")):
        return "terminal only"
    if presence in ("running", "idle"):
        return presence
    if ref[0] == "saved":
        return "frozen"
    if ref[0] == "agent" and session_id:
        return "resumable"
    return "closed terminal" if ref[0] == "terminal" else "unavailable"


