    def refresh_agents(self):
        """Ask AgentsView for a fresh catalog; never persist it to sessions.toml."""
        self.refresh_claude_peers()
        if self.agent_list_process and self.agent_list_process.state() != QProcess.NotRunning:
            self.agent_refresh_pending = True
            return
        self.agent_refresh_pending = False
        self.group_catalog_requested = True
        self.status.setText("Querying AgentsView…")
        process = QProcess(self)
        self.agent_list_process = process
        process.finished.connect(lambda code, _status: self.agent_list_finished(process, code))
        process.errorOccurred.connect(lambda error: self.agent_query_error(process, error))
        args = ["session", "list", "--json", "--limit", "500", "--sort", "recent"]
        self.agent_list_started_at = time.monotonic()
        console_log("INFO", "AgentsView catalog query starting")
        process.start("agentsview", args)

    def agent_query_error(self, process, error):
        if not isValid(process):
            return
        if error == QProcess.FailedToStart:
            self.status.setText("AgentsView could not be started; check that it is installed.")
            console_log("ERROR", "AgentsView catalog query could not start "
                        f"after {time.monotonic() - self.agent_list_started_at:.3f}s")
            if process is self.agent_list_process:
                self.agent_list_process = None
            process.deleteLater()

    def agent_list_finished(self, process, code):
        if not isValid(process):
            return
        output = bytes(process.readAllStandardOutput()).decode("utf-8", "replace")
        error = bytes(process.readAllStandardError()).decode("utf-8", "replace").strip()
        if process is self.agent_list_process:
            self.agent_list_process = None
        process.deleteLater()
        if code:
            self.status.setText("AgentsView query failed; see console log.")
            console_log("ERROR", f"AgentsView catalog query failed rc={code} "
                        f"elapsed={time.monotonic() - self.agent_list_started_at:.3f}s: {error}")
            return
        try:
            payload = json.loads(output)
            rows = payload.get("sessions", []) if isinstance(payload, dict) else payload
            if not isinstance(rows, list):
                raise ValueError("AgentsView returned no session list")
        except (ValueError, TypeError) as failure:
            self.status.setText("AgentsView returned invalid session data.")
            console_log("ERROR", f"AgentsView catalog parse failed elapsed="
                        f"{time.monotonic() - self.agent_list_started_at:.3f}s: {failure}")
            return
        self.agent_rows = [row for row in rows if isinstance(row, dict)
                           and agent_catalog.resume_argv(row)]
        catalog_fetched_at = time.monotonic()
        console_log("INFO", f"AgentsView catalog fetched elapsed="
                    f"{catalog_fetched_at - self.agent_list_started_at:.3f}s "
                    f"sessions={len(self.agent_rows)}")
        self.agent_by_id = {row["id"]: row for row in self.agent_rows}
        self._shown_ref = None
        self.refresh_tags()
        self.refresh_list()
        console_log("INFO", f"AgentsView catalog applied render="
                    f"{time.monotonic() - catalog_fetched_at:.3f}s "
                    f"total={time.monotonic() - self.agent_list_started_at:.3f}s")
        self.status.setText(f"AgentsView: {len(self.agent_rows)} resumable sessions · queried now")
        if self.agent_refresh_pending:
            self.refresh_agents()

