    def refresh_navigation(self):
        """Rebuild only the organization tree; cards remain a separate model."""
        selected = self.navigation_ref()
        tree = self.navigation
        tree.blockSignals(True)
        tree.clear()
        positions = {}

        def add(parent, ref, label, collapsed=False):
            item = QTreeWidgetItem([label])
            item.setData(0, NavigationTree.RefRole, list(ref))
            item.setToolTip(0, "Drop sessions here to set their direct domain; "
                            "drop groups here to set their domain"
                            if ref[0] == "domain" else
                            "Double-click or ←/→ to expand or collapse; drop sessions here"
                            if ref[0] in ("group", "section") else
                            "Select to view sessions")
            if parent:
                parent.addChild(item)
            else:
                tree.addTopLevelItem(item)
            positions[ref] = item
            item.setExpanded(not collapsed)
            return item

        add(None, ("all", ""), "All sessions")
        add(None, ("standing", ""), "Standing")
        domains = add(None, ("domains", ""), "Domains")
        domain_nodes = {domain["id"]: add(domains, ("domain", domain["id"]),
                                           domain["name"], domain["collapsed"])
                        for domain in self.groups.domains}
        without = add(None, ("no_domain", ""), "Groups without a domain")
        for group in self.groups.groups:
            parent = domain_nodes.get(group.get("domain"), without)
            domain = self.groups.get_domain(group.get("domain"))
            prefix = f"{domain['name']}::" if domain else ""
            label = group["name"].removeprefix(prefix) if prefix else group["name"]
            group_item = add(parent, ("group", group["id"]), label, group["collapsed"])
            if label != group["name"]:
                group_item.setToolTip(0, group["name"])
            for section in self.groups.sections_for(group["id"]):
                add(group_item, ("section", section["id"]), section["name"],
                    section["collapsed"])
            if self.groups.sections_for(group["id"]):
                add(group_item, ("unsectioned", group["id"]), "Unsectioned")
        for domain in self.groups.domains:
            add(domain_nodes[domain["id"]], ("domain_ungrouped", domain["id"]),
                "Not in a group")
        add(None, ("ungrouped", ""), "Ungrouped")
        add(None, ("retired", ""), "Set aside")
        tree.setCurrentItem(positions.get(selected) or positions[("ungrouped", "")])
        self._navigation_ref = tree.ref_for(tree.currentItem())
        self.update_search_placeholder()
        tree.blockSignals(False)
        popup = self.popup_navigation
        popup.blockSignals(True)
        popup.clear()
        popup_positions = {}

        def clone(item, parent=None):
            copy = QTreeWidgetItem([item.text(0)])
            ref = tree.ref_for(item)
            copy.setData(0, NavigationTree.RefRole, list(ref))
            copy.setToolTip(0, item.toolTip(0))
            if parent:
                parent.addChild(copy)
            else:
                popup.addTopLevelItem(copy)
            popup_positions[ref] = copy
            for index in range(item.childCount()):
                clone(item.child(index), copy)
            copy.setExpanded(item.isExpanded())

        for index in range(tree.topLevelItemCount()):
            clone(tree.topLevelItem(index))
        popup.setCurrentItem(popup_positions.get(self._navigation_ref))
        popup.blockSignals(False)

