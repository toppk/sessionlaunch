    def refresh_claude_peers(self):
        peers = claude_peers.read_peers()
        if peers != self.claude_peers:
            for session_id, previous in self.claude_peers.items():
                if session_id in peers:
                    continue
                pid = previous.get("pid")
                if not isinstance(pid, int):
                    continue
                try:
                    os.kill(pid, 0)
                except ProcessLookupError:
                    key = agent_session_key("claude", session_id)
                    if key and (self.observed_agent_keys is None or
                                key not in self.observed_agent_keys):
                        self.record_agent_stop(key)
                except PermissionError:
                    pass
            for session_id in peers:
                if key := agent_session_key("claude", session_id):
                    self.stop_alerts.discard(key)
            if not self.stop_alerts:
                self.stop_notice = ""
            self.claude_peers = peers
            self.refresh_list()

    def record_agent_stop(self, key):
        if key in self.stop_alerts or self.groups.is_retired([key]) or \
                self.groups.lifecycle_for([key])["on_stop"] != "notify":
            return
        self.stop_alerts.add(key)
        self.stop_notice = f"Agent stopped: {key}. No restart was attempted."
        self.status.setText(self.stop_notice)
        console_log("INFO", self.stop_notice)

