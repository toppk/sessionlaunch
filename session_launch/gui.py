class TitleBar(QWidget):
    def __init__(self):
        super().__init__()
        self._drag_at = None

    def mousePressEvent(self, event):
        if event.button() == Qt.LeftButton and self.window().windowHandle():
            if not self.window().windowHandle().startSystemMove():
                self._drag_at = event.globalPosition().toPoint()
        super().mousePressEvent(event)

    def mouseMoveEvent(self, event):
        if self._drag_at is not None and event.buttons() & Qt.LeftButton:
            position = event.globalPosition().toPoint()
            self.window().move(self.window().pos() + position - self._drag_at)
            self._drag_at = position
        super().mouseMoveEvent(event)

    def mouseReleaseEvent(self, event):
        self._drag_at = None
        super().mouseReleaseEvent(event)


class ResizeSurface(QWidget):
    """Give the frameless window usable resize borders on every edge."""

    def __init__(self):
        super().__init__()
        self.setMouseTracking(True)
        self._manual_edges = Qt.Edges()
        self._last_global = None
        QApplication.instance().installEventFilter(self)

    def eventFilter(self, watched, event):
        if (event.type() == QEvent.Enter and isinstance(watched, QWidget)
                and self.isAncestorOf(watched) and not self._manual_edges):
            self.unsetCursor()
        return super().eventFilter(watched, event)

    def edges_at(self, position):
        margin = 9
        edges = Qt.Edges()
        if position.x() < margin:
            edges |= Qt.LeftEdge
        elif position.x() >= self.width() - margin:
            edges |= Qt.RightEdge
        if position.y() < margin:
            edges |= Qt.TopEdge
        elif position.y() >= self.height() - margin:
            edges |= Qt.BottomEdge
        return edges

    def mousePressEvent(self, event):
        if event.button() == Qt.LeftButton:
            edges = self.edges_at(event.position().toPoint())
            handle = self.window().windowHandle()
            if edges and handle and not handle.startSystemResize(edges):
                self._manual_edges = edges
                self._last_global = event.globalPosition().toPoint()
        super().mousePressEvent(event)

    def mouseMoveEvent(self, event):
        if self._last_global is not None and event.buttons() & Qt.LeftButton:
            point = event.globalPosition().toPoint()
            delta = point - self._last_global
            geometry = self.window().geometry()
            if self._manual_edges & Qt.LeftEdge:
                geometry.setLeft(geometry.left() + delta.x())
            if self._manual_edges & Qt.RightEdge:
                geometry.setRight(geometry.right() + delta.x())
            if self._manual_edges & Qt.TopEdge:
                geometry.setTop(geometry.top() + delta.y())
            if self._manual_edges & Qt.BottomEdge:
                geometry.setBottom(geometry.bottom() + delta.y())
            if geometry.width() >= self.window().minimumWidth() and \
                    geometry.height() >= self.window().minimumHeight():
                self.window().setGeometry(geometry)
                self._last_global = point
        else:
            edges = self.edges_at(event.position().toPoint())
            horizontal = bool(edges & (Qt.LeftEdge | Qt.RightEdge))
            vertical = bool(edges & (Qt.TopEdge | Qt.BottomEdge))
            cursor = (Qt.SizeFDiagCursor if horizontal and vertical else
                      Qt.SizeHorCursor if horizontal else Qt.SizeVerCursor if vertical else
                      Qt.ArrowCursor)
            self.setCursor(cursor)
        super().mouseMoveEvent(event)

    def mouseReleaseEvent(self, event):
        self._manual_edges = Qt.Edges()
        self._last_global = None
        super().mouseReleaseEvent(event)

    def leaveEvent(self, event):
        # A cursor set on the parent otherwise carries over into child controls.
        self.unsetCursor()
        super().leaveEvent(event)


