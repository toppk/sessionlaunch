def foreground_chain(terminal):
    """Walk from the foreground host application through attached PTY parents."""
    processes = terminal.get("processes", terminal.get("process", []))
    by_pid = {process["pid"]: process for process in processes}
    pid = terminal.get("pid", 0)
    seen = set()
    while pid in by_pid and pid not in seen:
        seen.add(pid)
        process = by_pid[pid]
        yield process
        pid = process.get("ppid", 0)


def terminal_directory(terminal):
    """Return a usable directory and its provenance, without treating a PTY as a path."""
    if directory := terminal.get("cwd"):
        return directory, "Host CWD"
    if directory := terminal.get("pwd_env"):
        return directory, "Host PWD environment (may be stale)"
    for process in foreground_chain(terminal):
        if process.get("comm", "").removeprefix("-").casefold() not in SHELLS:
            continue
        if directory := process.get("cwd"):
            return directory, f"Attached {process['comm']} CWD (inferred)"
        if directory := process.get("pwd_env"):
            return directory, f"Attached {process['comm']} PWD (inferred; may be stale)"
    return "", "Unavailable"


def terminal_list_directory(terminal):
    directory, source = terminal_directory(terminal)
    if not directory:
        return "CWD unavailable"
    label = short_home(directory)
    return f"{label} (shell)" if source.startswith("Attached ") else label


