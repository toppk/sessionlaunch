    def card_geometry(self, option, index):
        """Use the same rectangles for painting and hover hit-testing."""
        card = option.rect.adjusted(4, 3, -4, -3)
        left, right = card.left() + 12, card.right() - 12
        top = card.top() + 9
        small_font = QFont(option.font)
        small_font.setPixelSize(max(10, 12 + self.window.zoom))
        small_metrics = QFontMetrics(small_font)
        header_height, note_height, footer_height, _ = card_row_metrics(
            option.font, self.window.zoom, bool(index.data(SessionListModel.NoteTextRole)))
        state = index.data(SessionListModel.CardPresenceRole)
        status_text = {"running": "running", "idle": "idle · shell",
                       "resumable": "resumable", "frozen": "frozen",
                       "terminal only": "unlinked" if card.width() < 300 else "terminal only",
                       "closed terminal": "closed terminal",
                       "record only": "record only"}.get(state, "unavailable")
        if not index.data(SessionListModel.RetiredDateRole) and state in (
                "resumable", "frozen", "closed terminal", "record only"):
            boot = index.data(SessionListModel.BootRole)
            if boot in ("always", "ask"):
                status_text = f"boot: {boot}"
        status_width = min(110, small_metrics.horizontalAdvance(status_text) + 2)
        status = QRect(right - status_width, top, status_width, header_height)
        keep_star = card_keep_star_rect(card, header_height)
        dot = QRect(left + 29, top + (header_height - 9) // 2, 9, 9)
        headline_left = left + 48
        roles = index.data(SessionListModel.RolesRole) or []
        role_text = " · ".join(roles)
        available = max(0, status.left() - headline_left - 10)
        oversees = index.data(SessionListModel.OverseesRole) or []
        headline_text = "o:" + oversees[0] if oversees else index.data(Qt.DisplayRole) or ""
        headline_font = QFont(option.font)
        headline_font.setStyleHint(QFont.Monospace)
        headline_font.setFamily("monospace")
        headline_font.setBold(True)
        desired_headline = QFontMetrics(headline_font).horizontalAdvance(headline_text) + 2
        role_width = min(120, small_metrics.horizontalAdvance(role_text) + 16) if role_text else 0
        if role_width and available - role_width - 7 < min(desired_headline, 120):
            if len(roles) > 1:
                role_text = f"r:{len(roles)}"
            role_width = min(small_metrics.horizontalAdvance(role_text) + 16,
                             max(0, available - min(desired_headline, 120) - 7))
            if role_width < 28:
                role_width = 0
        headline_width = min(max(0, available - role_width - (7 if role_width else 0)),
                             desired_headline)
        headline = QRect(headline_left, top, headline_width, header_height)
        role = QRect(headline.right() + 8, top + (header_height - small_metrics.height() - 6) // 2,
                     role_width, small_metrics.height() + 6) if role_width else None
        note_text = index.data(SessionListModel.NoteTextRole) or ""
        note_top = top + header_height + 3
        note = QRect(left, note_top, max(0, right - left), note_height) if note_text else None
        footer_top = top + header_height + (note_height + 3 if note else 0) + 4
        footer = []
        hits = []
        x = left
        entries = []
        provider = index.data(SessionListModel.ProviderRole) or ""
        repo = index.data(SessionListModel.RepoTagRole) or ""
        peer = index.data(SessionListModel.PeerNameRole) or ""
        if provider:
            entries.append(("provider", provider, ""))
        if index.data(SessionListModel.StandingRole):
            domain_id = index.data(SessionListModel.DomainRole)
            domain = self.window.groups.get_domain(domain_id) if domain_id else None
