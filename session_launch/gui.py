    def group_member_keys(self, ref, include_retired=False):
        if not ref:
            return []
        if ref[0] == "retired":
            return list(self.groups.retired)
        if ref[0] == "standing":
            return [key for key in self.groups.standing
                    if include_retired or not self.groups.is_retired([key])]
        if ref[0] == "domain":
            domain_groups = [group["id"] for group in self.groups.groups
                             if group.get("domain") == ref[1]]
            ordered = [key for group_id in domain_groups
                       for key in self.group_member_keys(("group", group_id), include_retired)]
            ordered.extend(key for key in self.groups.session_domains
                           if self.groups.domain_for([key]) == ref[1])
            ordered.extend(key for key in self.groups.standing
                           if ref[1] in self.groups.domains_for([key]))
            return [key for key in dict.fromkeys(ordered)
                    if include_retired or not self.groups.is_retired([key])]
        if ref[0] == "domain_ungrouped":
            return [key for key in self.group_member_keys(("domain", ref[1]), include_retired)
                    if not any((group := self.groups.get(group_id)) and
                               group.get("domain") == ref[1]
                               for group_id in self.groups.groups_for([key]))]
        if ref[0] not in ("group", "section", "unsectioned"):
            return []
        if ref[0] == "section":
            found = self.groups.section(ref[1])
            if not found:
                return []
            group_id, _ = found
            section_id = ref[1]
        else:
            group_id = ref[1]
            section_id = "" if ref[0] == "unsectioned" else None
        return [key for key, memberships in self.groups.memberships.items()
                if any(item["group"] == group_id and
                       (section_id is None or item["section"] == section_id)
                       for item in memberships) and
                (include_retired or not self.groups.is_retired([key]))]

    def scope_window_action(self, ref, action):
        keys = set(self.group_member_keys(ref))
        windows = {terminal.get("window_id") for terminal in self.live_data["terminal"]
                   if terminal.get("state") == "live" and terminal.get("window_id") and
                   terminal_session_key(terminal) in keys}
        for window_id in windows:
            self.act_window(window_id, action)
        if not windows:
            self.status.setText("No linked X11 windows in this section or group.")

    def group_member_view(self, key):
        catalog = next((row for row in self.agent_rows
                        if agent_session_key(row.get("agent"), row.get("id")) == key), None)
        terminals = [row for row in self.live_data["terminal"]
                     if terminal_session_key(row) == key]
        terminal = next((row for row in terminals if row.get("state") == "live"),
                        terminals[0] if terminals else None)
        saved = next((row for row in self.live_data.get("saved", [])
                      if key == f"saved:{row['id']}"), None)
        provider = "terminal"
        row = None
        ref = None
        if key.startswith("agent:"):
            _, provider, session_id = key.split(":", 2)
            observed_cwd = ((terminal.get("agent_cwd") or terminal.get("cwd"))
                            if terminal else "")
            row = catalog or {"id": session_id, "agent": provider,
                              "cwd": observed_cwd}
            ref = ("agent", row["id"])
        elif saved:
            provider = "frozen command"
            ref = ("saved", saved["id"])
        elif terminal:
            ref = ("terminal", terminal["key"])
            if terminal.get("agent") in ("claude", "codex") and terminal.get("state") == "live":
                provider = terminal["agent"]
        elif key.startswith("terminal:"):
            ref = ("terminal", key.removeprefix("terminal:"))
        elif key.startswith("saved:"):
            ref = ("saved", key.removeprefix("saved:"))
        annotation = self.groups.annotation_for([key])
        markers = annotation_markers(annotation)
        observed_cwd = ((terminal.get("agent_cwd") or terminal.get("cwd"))
                        if terminal else "")
        cwd = (row.get("cwd") if row else "") or \
            (saved.get("directory") if saved else "") or observed_cwd
        running = bool(terminal and terminal.get("state") == "live")
        if row and agent_session_key(provider, row["id"]) in self.terminals:
            running = True
        unlinked_agent = bool(terminal and terminal.get("state") == "live" and
                              provider in ("claude", "codex") and row is None)
        unlinked = (agent_catalog.unlinked_running_terminal({**row, "cwd": cwd},
                    self.live_data["terminal"]) if row and cwd and not running else None)
        peer = claude_peers.peer_for(row["id"], self.claude_peers) if row and provider == "claude" else None
        running = running or bool(peer)
        if row:
            title = row.get("display_name") or row.get("project") or row["id"]
        elif saved:
            title = saved["title"]
        elif terminal:
            title = terminal.get("host_application") or terminal.get("comm") or key
        else:
            title = key
        return {"key": key, "ref": ref, "row": row, "terminal": terminal,
                "provider": provider, "cwd": cwd or "", "repo": repo_tag_for(cwd) if cwd else None,
                "running": running, "title": title, "markers": markers, "peer": peer,
                "unlinked_agent": unlinked_agent, "blocked_by_unlinked": unlinked,
                "hierarchy": annotation_hierarchy_key(annotation),
                "resumable": bool(row and agent_catalog.resume_argv(row)),
                "can_revive": bool(row and agent_catalog.resume_argv(row) and cwd and
                                   agent_catalog.directory_available({"cwd": cwd}) and not running
                                   and not unlinked)}

