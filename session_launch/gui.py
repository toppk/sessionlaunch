def read_sessions(path):
    with path.open("rb") as stream:
        rows = tomllib.load(stream)["session"]
    sessions = []
    for row in rows:
        if row["agent"] not in ("claude", "codex"):
            raise ValueError(f"Unknown agent: {row['agent']}")
        sessions.append(Session(Path(row["repo"]), row["agent"], row["id"],
                                row.get("title", ""), row.get("confidence", ""),
                                row.get("last_active", "")))
    return sessions


