    def standing_agent_rows(self):
        """Keep known UUIDs visible beyond the live catalog limit."""
        rows = list(self.agent_rows)
        known = {agent_session_key(row.get("agent"), row.get("id")) for row in rows}
        keys = (set(self.groups.standing) | set(self.groups.memberships) |
                set(self.groups.session_domains) | set(self.groups.annotations) |
                set(self.groups.lifecycle) | set(self.groups.retired) |
                {terminal_session_key(item) for item in self.live_data["terminal"]})
        for key in sorted(keys):
            if key in known or not key.startswith("agent:"):
                continue
            _, provider, session_id = key.split(":", 2)
            if provider not in ("codex", "claude"):
                continue
            row_id = f"codex:{session_id}" if provider == "codex" else session_id
            terminal = next((item for item in self.live_data["terminal"]
                             if terminal_session_key(item) == key), None)
            row = {"id": row_id, "agent": provider,
                   "cwd": (terminal.get("agent_cwd") or terminal.get("cwd") or "")
                          if terminal else "",
                   "display_name": f"Session {session_id[:8]}",
                   "project": "", "message_count": 0}
