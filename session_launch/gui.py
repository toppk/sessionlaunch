def elevation_reason(terminal):
    """Identify a user switch in the foreground chain or an observed UID change."""
    if terminal.get("state") != "live":
        return ""
    for process in foreground_chain(terminal):
        command = process.get("comm", "").removeprefix("-").casefold()
        if command in USER_SWITCHERS:
            return f"Via {process['comm']} in foreground process chain"
    uid, euid = terminal.get("uid", -1), terminal.get("euid", -1)
    if uid >= 0 and euid >= 0 and uid != euid:
        return f"Setuid process: UID {uid}, effective UID {euid}"
    if euid >= 0 and euid != os.geteuid():
        return f"Effective UID {euid} differs from SessionLaunch UID {os.geteuid()}"
    return ""


